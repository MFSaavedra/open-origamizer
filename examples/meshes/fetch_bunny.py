"""Download the Stanford bunny and simplify it into a low-poly test mesh.

Run from the repository root (needs network access and the built package):

    uv run python examples/meshes/fetch_bunny.py [--faces 374]

Writes examples/meshes/bunny.obj, which git ignores. The Stanford 3D Scanning
Repository allows research use and free redistribution, but not commercial use
without permission; that does not fit this GPL-3.0 repository, so the mesh is
generated locally instead of committed.

Source: Stanford Computer Graphics Laboratory,
https://graphics.stanford.edu/data/3Dscanrep/ (bun_zipper.ply, the full
resolution reconstruction). The coarser reconstructions in the same archive
are not 2-manifolds, so the full one is simplified instead. It contains
vertices that no face uses; this script drops them explicitly, and everything
else goes through the normal checks. 374 faces matches the bunny of SoCG17
Fig. 1.
"""

import argparse
import io
import tarfile
import urllib.request
from pathlib import Path

import origamizer as og

URL = "https://graphics.stanford.edu/pub/3Dscanrep/bunny.tar.gz"
MEMBER = "bunny/reconstruction/bun_zipper.ply"
OUTPUT = Path(__file__).resolve().parent / "bunny.obj"


def read_ascii_ply(text):
    """Vertices (x, y, z) and faces of an ASCII PLY file with vertex and face elements."""
    lines = text.splitlines()
    end = lines.index("end_header")
    header = lines[:end]
    if "format ascii 1.0" not in header:
        raise ValueError("expected an ASCII PLY file")
    counts = {words[1]: int(words[2]) for words in (line.split() for line in header)
              if words and words[0] == "element"}
    body = lines[end + 1:]
    nv, nf = counts["vertex"], counts["face"]
    points = [[float(x) for x in body[i].split()[:3]] for i in range(nv)]
    faces = []
    for line in body[nv:nv + nf]:
        words = [int(x) for x in line.split()]
        if words[0] != len(words) - 1:
            raise ValueError(f"face record with a wrong vertex count: {line!r}")
        faces.append(words[1:])
    return points, faces


def drop_unused_vertices(points, faces):
    """Remove vertices that no face uses and renumber the faces."""
    used = sorted({i for face in faces for i in face})
    new_index = {old: new for new, old in enumerate(used)}
    return ([points[i] for i in used], [[new_index[i] for i in face] for face in faces],
            len(points) - len(used))


def write_obj(path, mesh, faces_wanted):
    lines = [
        "# Stanford Bunny, simplified to at most %d triangles." % faces_wanted,
        "# Source: Stanford Computer Graphics Laboratory, "
        "https://graphics.stanford.edu/data/3Dscanrep/ (bun_zipper.ply).",
        "# Terms: research use and free redistribution allowed; no commercial use without "
        "permission.",
        "# Generated by examples/meshes/fetch_bunny.py; not committed to the repository.",
    ]
    lines += ["v " + " ".join(f"{c:.9g}" for c in p) for p in mesh.points]
    lines += ["f " + " ".join(str(i + 1) for i in face) for face in mesh.faces]
    path.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description="Fetch and simplify the Stanford bunny.")
    parser.add_argument("--faces", type=int, default=374, help="target number of triangles")
    parser.add_argument("--out", type=Path, default=OUTPUT)
    args = parser.parse_args()

    with urllib.request.urlopen(URL, timeout=120) as response:
        archive = tarfile.open(fileobj=io.BytesIO(response.read()), mode="r:gz")
    with archive:
        text = archive.extractfile(MEMBER).read().decode("ascii")

    points, faces = read_ascii_ply(text)
    points, faces, dropped = drop_unused_vertices(points, faces)
    print(f"read {MEMBER}: {len(points)} vertices, {len(faces)} faces "
          f"({dropped} unused vertices dropped)")
    full = og.prepare_mesh(og.PolygonSoup(points, faces)).mesh
    low = og.prepare_mesh(og.to_soup(og.simplify_triangle_mesh(full, args.faces))).mesh
    write_obj(args.out, low, args.faces)
    t = low.topology()
    print(f"wrote {args.out}: {t.vertices} vertices, {t.faces} faces, genus {t.genus}, "
          f"{t.boundary_loops} boundary loops")


if __name__ == "__main__":
    main()
